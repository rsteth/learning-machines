"""Regenerate the small cl100k_base example fixture; no model inference."""
import json
from importlib.metadata import version
from pathlib import Path
import tiktoken

if version('tiktoken') != '0.14.0':
    raise RuntimeError('Use tiktoken==0.14.0 for this fixture')
encoding = tiktoken.get_encoding('cl100k_base')
texts = ['The cat sat on the', ' mat', ' floor', ' sofa', '.',
         'The cat sat on the mat.', 'unhappiness', 'antidisestablishmentarianism',
         ' king', ' slept', ' bed', ' throne']
# Pieces the teaching model treats as one token each. A piece that splits cannot be used as-is.
single = [' cat', ' king', ' sat', ' slept', ' on', ' the', ' mat', ' sofa', ' floor', ' bed', ' throne', '.']
for piece in single:
    assert len(encoding.encode(piece)) == 1, f'{piece!r} is not a single cl100k_base token'
examples = []
for text in texts:
    ids = encoding.encode(text)
    pieces = [encoding.decode([token]) for token in ids]
    assert encoding.decode(ids) == text
    examples.append(dict(text=text, ids=ids, pieces=pieces))
fixture = dict(schemaVersion=1, package='tiktoken', version=version('tiktoken'),
               encoding='cl100k_base', source='https://github.com/openai/tiktoken',
               examples=examples)
output = '// Generated by regenerate_fixture.py; tokenization only, not model output.\n'
output += 'export const FIXTURE = ' + json.dumps(fixture, indent=2, ensure_ascii=False) + ';\n'
Path(__file__).with_name('fixture.mjs').write_text(output, encoding='utf-8')
